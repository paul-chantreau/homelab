"""Match the installation disk by stable identifiers.

The largest disk is never a candidate. Kernel names such as /dev/sda are never
accepted as selectors.
"""

from __future__ import annotations

from typing import Any
from pathlib import Path
import re

import yaml


def bind_verified_disk(path: Path, device: dict[str, Any]) -> None:
    """Bind Subiquity to the device just verified by stable hardware identity.

    User configuration never accepts a kernel name as identity. Only the
    early-command, after exactly one match, may replace the refusal selector.
    An exact runtime path avoids unsupported WWN/by-id match directives and
    different short/full udev serial formats.
    """
    from maas_deploy.autoinstall import REFUSAL_SERIAL
    from maas_deploy.files import atomic_write

    name = str(device.get("name", ""))
    if not re.fullmatch(r"[A-Za-z0-9_.-]+", name):
        raise ValueError("Invalid verified disk name")
    selected = {"path": f"/dev/{name}"}
    try:
        document = yaml.safe_load(path.read_text(encoding="utf-8"))
        if not isinstance(document, dict):
            raise ValueError("Installer configuration must be a mapping")
        config = document.get("autoinstall", document)
        layout = config["storage"]["layout"]
        match = layout["match"]
        if match not in ({"serial": REFUSAL_SERIAL}, selected):
            raise ValueError("Installer selector was not generated by the verified-disk guard")
        layout["match"] = selected
    except (KeyError, TypeError, yaml.YAMLError) as error:
        raise ValueError("Invalid installer storage configuration") from error
    atomic_write(path, yaml.safe_dump(document, sort_keys=False))


def matching_disks(devices: list[dict[str, Any]], spec: dict[str, Any]) -> list[dict[str, Any]]:
    serial = _norm(spec.get("serial"))
    wwn = _norm_wwn(spec.get("wwn"))
    by_id = spec.get("by_id")
    model = _norm(spec.get("model"))
    if not serial and not wwn and not by_id:
        return []
    found = []
    for device in devices:
        if device.get("install_media") or device.get("mounted"):
            continue
        if device.get("type") not in {None, "disk"}:
            continue
        if serial and _norm(device.get("serial")) != serial:
            continue
        if wwn and _norm_wwn(device.get("wwn")) != wwn:
            continue
        if by_id and by_id not in set(device.get("by_id_paths") or []):
            continue
        if model and _norm(device.get("model")) != model:
            continue
        found.append(device)
    return found


def describe(device: dict[str, Any]) -> str:
    name = device.get("name") or device.get("kname") or "unknown"
    serial = device.get("serial") or "no-serial"
    wwn = device.get("wwn") or "no-wwn"
    model = device.get("model") or "no-model"
    size = device.get("size") or "unknown-size"
    return f"{name} model={model} serial={serial} wwn={wwn} size={size}"


def _norm(value: Any) -> str:
    if value in (None, ""):
        return ""
    return str(value).strip().lower()


def _norm_wwn(value: Any) -> str:
    text = _norm(value)
    if text.startswith("0x"):
        text = text[2:]
    return text
